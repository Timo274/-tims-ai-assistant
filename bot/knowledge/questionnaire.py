def format_questions_for_user() -> str:
    """Return the questionnaire as a single text blob, ready to be sent
    to the owner as a `.txt` attachment or pasted into a chat."""
    out: list[str] = [
        "Это анкета, чтобы бот мог отвечать так, как ответил бы ты сам.",
        "Заполняй свободным текстом — короткими предложениями. Что не хочешь раскрывать — пропусти.",
        "Когда заполнишь — пришли всё одним сообщением: `/set_knowledge` затем твой текст.",
        "",
    ]
    qnum = 0
    for section, items in QUESTIONNAIRE:
        out.append("")
        out.append(f"=== {section} ===")
        for q in items:
            qnum += 1
            out.append(f"{qnum}. {q}")
    out.append("")
    out.append(f"Всего вопросов: {qnum}.")
    return "\n".join(out)


async def get_user_knowledge(db: Database) -> str | None:
    async with db.session() as session:
        repo = Repository(session)
        return await repo.get_state(KNOWLEDGE_KEY)


async def set_user_knowledge(db: Database, value: str) -> None:
    async with db.session() as session:
        repo = Repository(session)
        await repo.set_state(KNOWLEDGE_KEY, value.strip())
        await session.commit()
